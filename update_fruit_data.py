ws_f2 = wb2['水果产品库']
ws_r2 = wb2['产区映射表']
ws_c2 = wb2['成熟度曲线']

# Build fruits array (same format as EMBEDDED_DATA)
fruits_json = []
for r in range(2, ws_f2.max_row + 1):
    fid = ws_f2.cell(r, 1).value
    if not fid: continue
    row = []
    for c in range(1, 18):
        val = ws_f2.cell(r, c).value
        row.append(str(val).strip() if val is not None else '')
    fruits_json.append(row)

# Build regions array
regions_json = []
for r in range(2, ws_r2.max_row + 1):
    adcode = ws_r2.cell(r, 1).value
    if not adcode: continue
    row = []
    for c in range(1, 10):
        val = ws_r2.cell(r, c).value
        row.append(str(val).strip() if val is not None else '')
    regions_json.append(row)

# Build curves array
curves_json = []
for r in range(2, ws_c2.max_row + 1):
    name = ws_c2.cell(r, 1).value
    if not name: continue
    row = [str(name).strip()]
    for c in range(2, 14):
        val = ws_c2.cell(r, c).value
        row.append(str(int(val)) if val is not None else '0')
    curves_json.append(row)

embedded = {'fruits': fruits_json, 'regions': regions_json, 'curves': curves_json}
embedded_json = json.dumps(embedded, ensure_ascii=False, separators=(',', ':'))

print(f'\nGenerated embedded data: {len(fruits_json)} fruits, {len(regions_json)} regions, {len(curves_json)} curves')

