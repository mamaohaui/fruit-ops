def style_header(ws, row, ncols):
    for c in range(1, ncols + 1):
        cell = ws.cell(row=row, column=c)
        cell.font = header_font
        cell.fill = header_fill
        cell.alignment = header_align
        cell.border = thin_border

def style_data(ws, start, end, ncols):
    for r in range(start, end + 1):
        for c in range(1, ncols + 1):
            cell = ws.cell(row=r, column=c)
            cell.font = cell_font
            cell.alignment = cell_align
            cell.border = thin_border

def auto_width(ws, ncols, min_w=8, max_w=42):
    for c in range(1, ncols + 1):
        best = min_w
        for row in ws.iter_rows(min_col=c, max_col=c, values_only=True):
            for v in row:
                if v:
                    best = max(best, min(len(str(v)) * 1.3 + 2, max_w))
        ws.column_dimensions[get_column_letter(c)].width = best


