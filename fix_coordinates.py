def process():
    src_path = '.reasonix/attachments/clipboard-20260707-160659.175227-000001.xlsx'
    dst_path = '.reasonix/attachments/clipboard-20260707-160659.175227-000001.xlsx'
    
    wb = openpyxl.load_workbook(src_path)
    ws = wb['产区映射表']
    
    # 读取所有现有行
    header = [c.value for c in ws[1]]
    
    existing_rows = []
    zero_rows = []  # (row_index, row_values)
    for row_idx, row in enumerate(ws.iter_rows(min_row=2, max_row=ws.max_row, values_only=True), start=2):
        row_list = list(row)
        if row_list[0] == '000000000':
            zero_rows.append((row_idx, row_list))
        else:
            existing_rows.append(row_list)
    
    # 处理每个 000000000 行
    new_rows = []
    stats = {"split": 0, "filled_city": 0, "filled_coord": 0, "unchanged": 0}
    
    for row_idx, row in zero_rows:
        admin_code = row[0]
        province = row[1]
        city = row[2]
        district_raw = row[3]
        town = row[4]
        lon = row[5]
        lat = row[6]
        fruit_id = row[7]
        level = row[8]
        
        # 解析多产区
        locations = parse_multi_location(district_raw)
        
        if len(locations) <= 1 and not locations:
            # 简单单产区：直接补坐标
            info = lookup(district_raw)
            if info:
                if not city:
                    city = info[2]
                    stats["filled_city"] += 1
                new_admin = generate_admin_code(province, city, district_raw)
                new_rows.append([new_admin, province, city, district_raw, town,
                                info[0], info[1], fruit_id, level])
                stats["filled_coord"] += 1
            else:
                new_rows.append(row)
                stats["unchanged"] += 1
        elif len(locations) == 1:
            # 单产区
            d_name, d_city = locations[0]
            info = lookup(d_name)
            if info:
                actual_city = d_city or info[2]
                new_admin = generate_admin_code(info[3], actual_city, d_name)
                new_rows.append([new_admin, info[3], actual_city, d_name, town,
                                info[0], info[1], fruit_id, level])
                stats["filled_coord"] += 1
                if d_city:
                    stats["filled_city"] += 1
            else:
                new_rows.append(row)
                stats["unchanged"] += 1
        else:
            # 多产区：拆分为多行
            for d_name, d_city in locations:
                info = lookup(d_name)
                if info:
                    actual_city = d_city or info[2]
                    actual_province = info[3]
                    new_admin = generate_admin_code(actual_province, actual_city, d_name)
                    new_rows.append([new_admin, actual_province, actual_city, d_name, town,
                                    info[0], info[1], fruit_id, level])
                else:
                    # 无法查找，保留原始
                    new_rows.append(["000000000", province, d_city, d_name, town,
                                    0, 0, fruit_id, level])
            stats["split"] += 1
    
    # 合并：已有正确行 + 新生成的行
    all_rows = existing_rows + new_rows
    
    # 清除旧数据（保留表头）
    ws.delete_rows(2, ws.max_row - 1)
    
    # 写入新数据
    for i, row_data in enumerate(all_rows, start=2):
        for j, val in enumerate(row_data, start=1):
            ws.cell(row=i, column=j, value=val)
    
    # 保存
    wb.save(dst_path)
    
    print(f"处理完成！")
    print(f"  拆分多产区行: {stats['split']} 行 → 拆分为多行")
    print(f"  补全市字段: {stats['filled_city']} 行")
    print(f"  补全坐标: {stats['filled_coord']} 行")
    print(f"  总行数变化: {len(zero_rows)} → {len(new_rows)} 行")
    print(f"  最终总行数: {len(all_rows)}")
    
    # 验证
    verify(wb)


