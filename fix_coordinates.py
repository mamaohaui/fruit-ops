def lookup(name):
    """查询坐标数据库，返回 (lon, lat, city, province, code_prefix)"""
    if name in COORDINATE_DB:
        return COORDINATE_DB[name]
    # 尝试去掉"市"后缀
    if name.endswith("市"):
        base = name[:-1]
        if base in COORDINATE_DB:
            return COORDINATE_DB[base]
    # 尝试加上"市"后缀
    if (name + "市") in COORDINATE_DB:
        return COORDINATE_DB[name + "市"]
    # 尝试加上"县"后缀
    if (name + "县") in COORDINATE_DB:
        return COORDINATE_DB[name + "县"]
    return None


def parse_multi_location(text):
    """
    解析复合产区文本，返回 [(区县名, 所属市), ...] 列表。
    支持模式：
    - "眉山市（丹棱县、东坡区）、蒲江县、金堂县"
    - "丹棱县、蒲江县、名山区"
    - "成都市（龙泉驿区、双流区）、雅安市石棉县"
    - "安岳县（中国柠檬之乡）"
    - "海口市（火山荔枝）"
    """
    if not text:
        return []
    
    # 清理注释性括号内容
    text = re.sub(r'（(?:中国.*?|火山.*?|潞江.*?)）', '', text)
    
    results = []
    
    # 模式1: "XX市（aa、bb）、YY县"
    # 匹配 "城市名（子区域1、子区域2）" 模式
    pattern1 = re.findall(r'([^\s、（,，]+)(?:市|州|地区)?（([^）]+)）', text)
    for city_base, subs in pattern1:
        city_name = city_base + "市" if not city_base.endswith(("市", "州", "地区")) else city_base
        # 修正：去掉city_base中可能被误加的后缀
        for sub in re.split(r'[、,，]', subs):
            sub = sub.strip()
            if sub:
                results.append((sub, city_name))
    
    if pattern1:
        # 移除已匹配的 "XX市（...）" 部分
        text = re.sub(r'[^\s、（,，]+(?:市|州|地区)?（[^）]+）', '', text)
    
    # 模式2: 剩余的独立地名（用、或，分隔）
    text = text.strip().strip('、，,')
    remaining = re.split(r'[、,，]', text)
    for item in remaining:
        item = item.strip()
        if not item:
            continue
        # 如果是城市名（以"市"或"州"结尾），直接用城市坐标
        if item.endswith(("市", "州")):
            results.append((item, item))
        else:
            # 区县名，需要查表确定所属市
            info = lookup(item)
            if info:
                results.append((item, info[2]))  # info[2] is city
            else:
                results.append((item, None))
    
    return results


def generate_admin_code(province, city, district):
    """生成9位行政区域代码（简化版：前6位区县代码+000）"""
    # 先查数据库获取前6位代码
    info = lookup(district)
    if info and info[4]:
        return info[4] + "000"
    
    # 如果区县名就是地级市名，使用城市代码
    district_clean = district.rstrip("市州县区")
    city_clean = city.rstrip("市州县区") if city else ""
    
    if district_clean == city_clean or district == city:
        city_info = lookup(city)
        if city_info and city_info[4]:
            return city_info[4] + "000"
    
    return "000000000"


